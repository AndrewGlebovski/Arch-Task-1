from typing import Protocol
from .student import Student
from .evaluation import Evaluation
from .rubric import Rubric
from .values import StudentId, EvaluationId


class StudentRepository(Protocol):
    def save(self, student: Student) -> None: ...
    def find(self, sid: StudentId) -> Student | None: ...
    def all(self) -> list[Student]: ...


class RubricRepository(Protocol):
    def get(self) -> Rubric: ...
    def save(self, rubric: Rubric) -> None: ...


class EvaluationRepository(Protocol):
    def save(self, evaluation: Evaluation) -> None: ...
    def find(self, eid: EvaluationId) -> Evaluation | None: ...
    def by_student(self, sid: StudentId) -> list[Evaluation]: ...
    def all(self) -> list[Evaluation]: ...
    def delete(self, eid: EvaluationId) -> None: ...
